export type MockScenarioKind =
  | 'default'
  | 'approval'
  | 'fail'
  | 'disconnect'
  | 'duplicate'
  | 'slow-cancel'
  | 'early-cancel'

export interface MockApprovalSpec {
  approvalId: string
  title: string
  command: string
  risk: 'low' | 'medium' | 'high'
}

export interface MockScenarioPlan {
  kind: MockScenarioKind
  initialPauseMs: number
  chunkDelayMs: number
  chunks: string[]
  emitTool?: {
    toolCallId: string
    toolName: string
    summary: string
  }
  approval?: MockApprovalSpec
  postApprovalChunks?: string[]
  failAfterChunks?: {
    code: string
    message: string
  }
  hangIndefinitely?: boolean
  duplicateEventTest?: boolean
}

export function detectMockScenario(prompt: string): MockScenarioKind {
  const lower = prompt.toLowerCase()
  if (lower.includes('early-cancel')) return 'early-cancel'
  if (lower.includes('slow-cancel')) return 'slow-cancel'
  if (lower.includes('disconnect')) return 'disconnect'
  if (lower.includes('duplicate')) return 'duplicate'
  if (lower.includes('approval')) return 'approval'
  if (lower.includes('fail')) return 'fail'
  return 'default'
}

export function buildMockScenarioPlan(
  prompt: string,
  botName: string,
  workspacePath: string,
): MockScenarioPlan {
  const kind = detectMockScenario(prompt)
  const preview = prompt.trim().slice(0, 80)

  switch (kind) {
    case 'early-cancel':
      return {
        kind,
        initialPauseMs: 250,
        chunkDelayMs: 40,
        chunks: [
          `[Mock ${botName}] `,
          'Preparing response for: ',
          `"${preview}".`,
        ],
      }

    case 'slow-cancel':
      return {
        kind,
        initialPauseMs: 20,
        chunkDelayMs: 70,
        chunks: [
          `[Mock ${botName}] `,
          'Starting slow streamed execution... ',
          'Step 1 complete. ',
          'Step 2 complete. ',
          'Step 3 complete. ',
          'Step 4 complete. ',
          'Step 5 complete. ',
          'Step 6 complete. ',
          'Step 7 complete. ',
          'All steps finished.',
        ],
      }

    case 'approval':
      return {
        kind,
        initialPauseMs: 15,
        chunkDelayMs: 20,
        chunks: [
          `[Mock ${botName}] Inspecting workspace \`${workspacePath}\` before applying a simulated change.\n\n`,
        ],
        emitTool: {
          toolCallId: 'mock_tool_1',
          toolName: 'mock_workspace_plan',
          summary: `Simulated plan in ${workspacePath}`,
        },
        approval: {
          approvalId: 'mock_approval_1',
          title: 'Approve simulated workspace write',
          command: 'mock-write ./NOTES.md (simulation only, no disk write)',
          risk: 'medium',
        },
        postApprovalChunks: [
          'Approval granted. ',
          'Simulated workspace update completed cleanly with zero real side effects.',
        ],
      }

    case 'fail':
      return {
        kind,
        initialPauseMs: 15,
        chunkDelayMs: 20,
        chunks: [
          `[Mock ${botName}] Starting simulated task for "${preview}"...\n`,
        ],
        emitTool: {
          toolCallId: 'mock_tool_fail',
          toolName: 'mock_check',
          summary: 'Simulated preflight check',
        },
        failAfterChunks: {
          code: 'MOCK_EXECUTION_FAILED',
          message: 'Simulated runtime failure triggered by "fail" prompt keyword.',
        },
      }

    case 'disconnect':
      return {
        kind,
        initialPauseMs: 15,
        chunkDelayMs: 20,
        chunks: [
          `[Mock ${botName}] Streaming partial output before simulated daemon disconnect... `,
        ],
        hangIndefinitely: true,
      }

    case 'duplicate':
      return {
        kind,
        initialPauseMs: 10,
        chunkDelayMs: 15,
        chunks: [
          `[Mock ${botName}] Deduplicated event stream verified for "${preview}". `,
          'Duplicate event keys were safely ignored.',
        ],
        duplicateEventTest: true,
      }

    case 'default':
    default:
      return {
        kind: 'default',
        initialPauseMs: 15,
        chunkDelayMs: 20,
        chunks: [
          `[Mock ${botName}] `,
          `Received your request: "${preview}".\n\n`,
          'This response is generated by the **daemon-owned Mock Runtime** ',
          '(Phase 2A execution & persistence foundation — live AI inference is disabled).\n\n',
          `- Workspace: \`${workspacePath}\`\n`,
          '- Persistence: SQLite `sessions`, `runs`, `run_events`, `messages`',
        ],
        emitTool: {
          toolCallId: 'mock_tool_inspect',
          toolName: 'mock_inspect_context',
          summary: `Simulated context check for ${botName}`,
        },
      }
  }
}
